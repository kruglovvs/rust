//! Todo 11 evidence runner (host): drives the 4xx matrix through the real
//! `RtspServer` dispatch and prints `request → status` for
//! `.omo/evidence/task-11/error-responses.txt`.
//!
//! Exits non-zero if any row deviates from the plan's QA — failure contract
//! ("a malformed request line, a wrong `CSeq`, an unknown method and a
//! `Transport:` header the server does not offer each produce a correct RTSP
//! error response (4xx) rather than a dropped connection or a panic").
//!
//! Usage: `cargo run --bin task11_errors`
#![allow(dead_code)]

#[path = "../../firmware/src/session.rs"]
mod session;

#[path = "../../firmware/src/rtsp/mod.rs"]
mod rtsp;

use rtsp::server::{response_status, ConnIo, RtspServer};
use session::{Session as Lifecycle, SessionState};

const HOST: &str = "rtsp://192.168.1.5:554/mjpeg/1";

fn req(first_line: &str, headers: &[(&str, &str)]) -> Vec<u8> {
    let mut s = format!("{first_line}\r\n");
    for (k, v) in headers {
        s += &format!("{k}: {v}\r\n");
    }
    s.push_str("\r\n");
    s.into_bytes()
}

struct Matrix {
    failures: usize,
}

impl Matrix {
    fn row(&mut self, name: &str, request: &str, got: Option<u16>, expected: u16) {
        let ok = got == Some(expected);
        if !ok {
            self.failures += 1;
        }
        println!(
            "{:<58} | expect {} | got {:>4} | {}",
            format!("{name} [{request}]"),
            expected,
            got.map(|s| s.to_string()).unwrap_or_else(|| "-".into()),
            if ok { "PASS" } else { "FAIL" }
        );
    }

    fn assert_true(&mut self, name: &str, cond: bool) {
        if !cond {
            self.failures += 1;
        }
        println!(
            "{:<58} | expect {} | got {:>4} | {}",
            name,
            "true",
            if cond { "true" } else { "false" },
            if cond { "PASS" } else { "FAIL" }
        );
    }
}

fn dispatch(
    srv: &mut RtspServer,
    life: &mut Lifecycle,
    conn: u64,
    raw: &[u8],
) -> Option<u16> {
    let io = ConnIo::for_test();
    let (resp, _actions) = srv.handle_bytes(raw, conn, &io, life);
    response_status(&resp)
}

fn main() {
    println!("TASK 11 — RTSP 4xx error-response matrix");
    println!("Generated by harness bin task11_errors (HOST-EXECUTED, no board)");
    println!("Plan QA — failure (Todo 11), verbatim:");
    println!("  \"assert that a malformed request line, a wrong CSeq, an unknown method\"");
    println!("  \"and a Transport: header the server does not offer each produce a correct\"");
    println!("  \"RTSP error response (4xx) rather than a dropped connection or a panic.\"");
    println!();
    println!("{:<58} | {:<8} | {:<4} | {}", "REQUEST / SCENARIO", "EXPECTED", "GOT", "RESULT");
    println!("{}", "-".repeat(100));

    let mut m = Matrix { failures: 0 };
    let mut srv = RtspServer::with_defaults();
    let mut life = Lifecycle::with_defaults();

    // --- 400 class -------------------------------------------------------
    m.row(
        "malformed request line: 'garbage\\r\\n\\r\\n'",
        "garbage",
        dispatch(&mut srv, &mut life, 1, b"garbage\r\n\r\n"),
        400,
    );
    m.row(
        "wrong CSeq: missing header",
        "OPTIONS rtsp://h/mjpeg/1 RTSP/1.0 (no CSeq)",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req("OPTIONS rtsp://h/mjpeg/1 RTSP/1.0", &[]),
        ),
        400,
    );
    m.row(
        "wrong CSeq: non-numeric value 'not-a-number'",
        "OPTIONS rtsp://h/mjpeg/1 RTSP/1.0 CSeq: not-a-number",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req(
                "OPTIONS rtsp://h/mjpeg/1 RTSP/1.0",
                &[("CSeq", "not-a-number")],
            ),
        ),
        400,
    );
    m.row(
        "SETUP without a Transport: header",
        "SETUP .../trackID=0 (no Transport)",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req("SETUP rtsp://h/mjpeg/1/trackID=0 RTSP/1.0", &[("CSeq", "1")]),
        ),
        400,
    );
    m.row(
        "PLAY without a Session: header",
        "PLAY (no Session)",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req("PLAY rtsp://h/mjpeg/1 RTSP/1.0", &[("CSeq", "1")]),
        ),
        400,
    );
    m.row(
        "GET_PARAMETER without a Session: header",
        "GET_PARAMETER (no Session)",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req(
                "GET_PARAMETER rtsp://h/mjpeg/1 RTSP/1.0",
                &[("CSeq", "1")],
            ),
        ),
        400,
    );

    // --- 405 -------------------------------------------------------------
    m.row(
        "unknown method PAUSE",
        "PAUSE rtsp://h/mjpeg/1",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req("PAUSE rtsp://h/mjpeg/1 RTSP/1.0", &[("CSeq", "3")]),
        ),
        405,
    );

    // --- 404 -------------------------------------------------------------
    m.row(
        "DESCRIBE on a path that is not /mjpeg/1",
        "DESCRIBE rtsp://h/other",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req("DESCRIBE rtsp://h/other RTSP/1.0", &[("CSeq", "4")]),
        ),
        404,
    );
    m.row(
        "SETUP for an unknown track",
        "SETUP .../trackID=9",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req(
                "SETUP rtsp://h/mjpeg/1/trackID=9 RTSP/1.0",
                &[
                    ("CSeq", "5"),
                    ("Transport", "RTP/AVP/TCP;unicast;interleaved=0-1"),
                ],
            ),
        ),
        404,
    );

    // --- 406 -------------------------------------------------------------
    m.row(
        "DESCRIBE with Accept that is not application/sdp",
        "DESCRIBE Accept: application/xml",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req(
                "DESCRIBE rtsp://h/mjpeg/1 RTSP/1.0",
                &[("CSeq", "6"), ("Accept", "application/xml")],
            ),
        ),
        406,
    );

    // --- 461 -------------------------------------------------------------
    for (label, transport) in [
        ("raw/RAW (non-RTP transport)", "raw/RAW;unicast"),
        ("RTP/AVP multicast", "RTP/AVP;multicast;port=0-1"),
        ("RTP/AVP UDP without client_port", "RTP/AVP;unicast"),
    ] {
        m.row(
            &format!("Transport the server does not offer: {label}"),
            "SETUP .../trackID=0",
            dispatch(
                &mut srv,
                &mut life,
                1,
                &req(
                    "SETUP rtsp://h/mjpeg/1/trackID=0 RTSP/1.0",
                    &[("CSeq", "7"), ("Transport", transport)],
                ),
            ),
            461,
        );
    }
    m.assert_true("no session created by any 4xx above", srv.active_session().is_none());

    // --- happy SETUP (establishes the session the 453 rows need) ---------
    let (resp, _) = {
        let io = ConnIo::for_test();
        srv.handle_bytes(
            &req(
                "SETUP rtsp://h/mjpeg/1/trackID=0 RTSP/1.0",
                &[
                    ("CSeq", "8"),
                    ("Transport", "RTP/AVP/TCP;unicast;interleaved=0-1"),
                ],
            ),
            1,
            &io,
            &mut life,
        )
    };
    m.assert_true(
        "first client SETUP succeeds (200, session issued)",
        response_status(&resp) == Some(200) && resp.windows(9).any(|w| w == b"Session: "),
    );
    let session_id = {
        let text = String::from_utf8_lossy(&resp);
        text.lines()
            .find_map(|l| l.strip_prefix("Session: "))
            .map(|v| v.split(';').next().unwrap().trim().to_string())
            .unwrap_or_default()
    };

    m.row(
        "PLAY with the issued session (starts capture)",
        "PLAY Session: <issued>",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req(
                "PLAY rtsp://h/mjpeg/1 RTSP/1.0",
                &[("CSeq", "9"), ("Session", &session_id)],
            ),
        ),
        200,
    );
    m.assert_true(
        "lifecycle Active after first client's PLAY",
        life.state() == SessionState::Active,
    );

    // --- 453: single-session refusal ------------------------------------
    m.row(
        "second concurrent client SETUP (first session active)",
        "conn 2 SETUP .../trackID=0",
        dispatch(
            &mut srv,
            &mut life,
            2,
            &req(
                "SETUP rtsp://h/mjpeg/1/trackID=0 RTSP/1.0",
                &[
                    ("CSeq", "1"),
                    ("Transport", "RTP/AVP/TCP;unicast;interleaved=0-1"),
                ],
            ),
        ),
        453,
    );
    m.assert_true(
        "first session untouched after refusal (same id, owner 1, still Active)",
        srv.active_session().map(|a| a.id == session_id && a.owner == 1) == Some(true)
            && life.state() == SessionState::Active,
    );
    let disconnect_actions = srv.on_disconnect(2, &mut life);
    m.assert_true(
        "refused connection disconnect: no actions, first session intact",
        disconnect_actions.is_empty()
            && srv.active_session().map(|a| a.owner == 1) == Some(true)
            && life.state() == SessionState::Active,
    );

    // --- 454 -------------------------------------------------------------
    m.row(
        "PLAY with an unknown Session id",
        "PLAY Session: esp-dead",
        dispatch(
            &mut srv,
            &mut life,
            1,
            &req(
                "PLAY rtsp://h/mjpeg/1 RTSP/1.0",
                &[("CSeq", "10"), ("Session", "esp-dead")],
            ),
        ),
        454,
    );

    // --- CSeq echo contract ---------------------------------------------
    let (resp, _) = {
        let io = ConnIo::for_test();
        srv.handle_bytes(
            &req("OPTIONS rtsp://h/mjpeg/1 RTSP/1.0", &[("CSeq", "42")]),
            1,
            &io,
            &mut life,
        )
    };
    m.assert_true(
        "CSeq echoed verbatim in a 200 response (CSeq: 42)",
        resp.windows(10).any(|w| w == b"CSeq: 42\r\n"),
    );
    m.assert_true(
        "Server: header present in every response",
        String::from_utf8_lossy(&resp).contains("Server: "),
    );

    println!("{}", "-".repeat(100));
    if m.failures == 0 {
        println!("RESULT: PASS (all rows matched the plan's 4xx contract)");
    } else {
        println!("RESULT: FAIL ({} row(s) deviated)", m.failures);
        std::process::exit(1);
    }
}
